#!/usr/bin/env python3
"""Validate the portfolio data before it is published.

Everything derived from the data (page content, JSON-LD, profile.json,
llms.txt, sitemap.xml) is generated by build_content.py and cannot drift, so this only
checks what generation cannot guarantee: that the data is readable and
complete, and that every file and page it points to exists.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://raulesteveza.github.io"
ERRORS: list[str] = []

DATA_FILES = [
    "data/person.json",
    "data/experience.json",
    "data/education.json",
    "data/certificates.json",
    "data/bestProjects.json",
    "data/projects.json",
    "data/tools.json",
    "data/demos.json",
    "data/games.json",
]

PERSON_FIELDS = ["name", "title", "location", "website", "email", "github", "linkedin",
                 "llms_intro", "summary", "focus", "knows_about", "skills", "languages"]


def load_json(relative_path: str):
    """Read a JSON file given its path relative to the repository root."""
    return json.loads((ROOT / relative_path).read_text(encoding="utf-8"))


def check(condition: bool, message: str) -> None:
    """Record message as an error when condition is false.

    Errors are collected in ERRORS so a single run reports all of them.
    """
    if not condition:
        ERRORS.append(message)


def local_target(path: str) -> Path:
    """Map a site URL path to the file that serves it in the repository.

    A path ending in "/" is served by its index.html ('/tools/Mapper/' ->
    tools/Mapper/index.html). Query strings and fragments are ignored.
    """
    local = ROOT / urlparse(path).path.lstrip("/")
    return local / "index.html" if path.endswith("/") else local


def validate_data() -> dict:
    """Read every data file and check that person.json has its required fields.

    Returns:
        The parsed files keyed by their relative path. A file that cannot be read
        is missing from the result and recorded in ERRORS.
    """
    data = {}
    for relative_path in DATA_FILES:
        try:
            data[relative_path] = load_json(relative_path)
        except (OSError, json.JSONDecodeError) as error:
            ERRORS.append(f"Could not read {relative_path}: {error}")
    person = data.get("data/person.json", {})
    for field in PERSON_FIELDS:
        check(field in person, f"data/person.json is missing '{field}'")
    return data


def validate_published_entries(data: dict) -> None:
    """Every tool, demo (and its sitemap_pages) and game listed on the site must be deployed."""
    tools = [t for t in data["data/tools.json"]["tools"] if not t.get("hidden")]
    entries = (
        [(t["name"], t["tool_url"]) for t in tools]
        + [(d["name"], url) for d in data["data/demos.json"]["demos"]
           for url in [d["demo_url"], *(d.get("sitemap_pages") or [])]]
        + [(g["name"], g["game_url"]) for g in data["data/games.json"]["games"]]
    )
    for name, url in entries:
        check(local_target(url).exists(), f"{name}: missing deployed entry point {local_target(url).relative_to(ROOT)}")


def validate_education(data: dict) -> None:
    """Check that every logo referenced in education.json exists."""
    for item in data["data/education.json"]["education"]:
        for logo in item.get("logos") or []:
            check((ROOT / logo).is_file(), f"Missing education logo: {logo}")


def main() -> int:
    """Run all checks and print the result.

    The checks that read nested fields only run when every data file loaded,
    so a broken file is reported once instead of as a chain of KeyErrors.

    Returns:
        The process exit code: 0 when the data is valid, 1 otherwise.
    """
    data = validate_data()
    if not ERRORS:
        try:
            validate_published_entries(data)
            validate_education(data)
        except KeyError as error:
            ERRORS.append(f"Could not parse required content: {error}")

    if ERRORS:
        print("Content validation failed:", file=sys.stderr)
        for error in ERRORS:
            print(f"- {error}", file=sys.stderr)
        return 1

    print("Content validation passed: data is complete and every listed page and file exists.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
